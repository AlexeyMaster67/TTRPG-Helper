/**
 * Deterministically lookup an item from a specific DMG Magic Table using a d100 roll (1-100)
 */
export function lookupMagicTableItem(tableId: DmgMagicTableId, d100: number): {
  entry: DmgMagicTableEntry;
  bracketDesc: string;
} {
  const table = DMG_MAGIC_TABLES[tableId] || DMG_TABLE_A;
  const clampedRoll = Math.max(1, Math.min(100, Math.floor(d100)));

  for (const entry of table) {
    if (clampedRoll >= entry.rollMin && clampedRoll <= entry.rollMax) {
      return {
        entry,
        bracketDesc: `Таблица ${tableId} [${entry.rollMin < 10 ? '0' + entry.rollMin : entry.rollMin}–${entry.rollMax < 10 ? '0' + entry.rollMax : entry.rollMax}]`,
      };
    }
  }

  // Fallback to last entry
  const last = table[table.length - 1];
  return {
    entry: last,
    bracketDesc: `Таблица ${tableId} [${last.rollMin}–${last.rollMax}]`,
  };
}
