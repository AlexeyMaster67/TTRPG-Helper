// --- TYPES ---
export type CategoryTab =
  | 'conditions'
  | 'actions'
  | 'mastery'
  | 'classes'
  | 'species'
  | 'rest_damage';

interface ConditionRule {
  name: string;
  nameEn: string;
  desc: string;
  effects: string[];
}

interface ActionRule {
  name: string;
  nameEn: string;
  type: 'Action' | 'Bonus Action' | 'Reaction' | 'Movement';
  desc: string;
  details: string[];
  rule2024Note?: string;
}

interface WeaponMasteryRule {
  name: string;
  nameEn: string;
  weapons: string;
  mechanics: string;
  tactics: string;
  saveDC?: string;
}

interface ClassOverviewRule {
  name: string;
  nameEn: string;
  hitDie: string;
  primaryStat: string;
  saves: string;
  spellcaster: string;
  masteries: string;
  highlights: string[];
}

interface SpeciesRule {
  name: string;
  nameEn: string;
  size: string;
  speed: string;
  darkvision: string;
  traits: { title: string; desc: string }[];
}

interface RestDamageRule {
  title: string;
  category: 'rest' | 'death' | 'damage_types' | 'defenses' | 'cover' | 'environment';
  desc: string;
  bullets: string[];
}

